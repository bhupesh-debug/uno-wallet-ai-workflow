"""Synthetic weekly performance data for the Uno Wallet AI workflow demo.

All data is SYNTHETIC — generated by a seeded RNG, no real Uno Wallet data,
no real users. Eight weeks (2026-W01 .. 2026-W08). Three weeks carry
deliberate edge cases so the evaluation harness has real signal:

- W03: rec_accuracy_pct is MISSING (empty cell). The memo must say "n/a",
  never invent a number.
- W05: signups and transactions move by the SAME % (within the 0.5pp
  near-tie rule) — a tie for top mover. Any tied metric is an acceptable
  top-mover answer.
- W06: transactions is NEGATIVE (-50) — a data-quality fault. It must be
  flagged, never used in a calculation.
- W07: rec_accuracy_pct dips to 87% — below the 90% risk threshold, so the
  memo must raise a RISK_ACCURACY_LOW flag.
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

KPI_COLUMNS = [
    "signups",
    "activations",
    "active_users",
    "transactions",
    "gmv_usd",
    "points_earned",
    "rec_accuracy_pct",
    "failed_recs",
    "support_tickets",
]

WEEKS = [f"2026-W{i:02d}" for i in range(1, 9)]

FEEDBACK_POOL = [
    ("wrong_card", "App picked my 1% card instead of my 5% dining card at the restaurant."),
    ("wrong_card", "It used the wrong card again at the grocery store — lost about $4 in points."),
    ("card_not_recognised", "My new card does not show up in the wallet at all."),
    ("card_not_recognised", "Tried to add my credit card and it kept failing to verify."),
    ("slow_app", "The wallet takes a few seconds to open at the till, which is awkward."),
    ("slow_app", "App feels slow when I open it at checkout."),
    ("love_it", "Love not having to think about which card to tap. It just works."),
    ("love_it", "Earned more points this month than ever — the auto-pick is great."),
    ("rewards_confusing", "I do not understand why it picked that card — show me the maths."),
    ("rewards_confusing", "Can you explain the points breakdown after each purchase?"),
    ("onboarding", "Setup took a while — too many steps before my first tap."),
    ("onboarding", "Adding my first card was confusing; I almost gave up."),
]

BASE = {
    "signups": 320,
    "activations": 240,
    "active_users": 1400,
    "transactions": 5200,
    "gmv_usd": 310000.0,
    "points_earned": 420000,
    "rec_accuracy_pct": 93.0,
    "failed_recs": 180,
    "support_tickets": 42,
}

GROWTH = {
    "signups": 0.04,
    "activations": 0.04,
    "active_users": 0.05,
    "transactions": 0.06,
    "gmv_usd": 0.05,
    "points_earned": 0.05,
    "rec_accuracy_pct": 0.0,
    "failed_recs": -0.02,
    "support_tickets": -0.01,
}

NOISE = {
    "signups": 0.06,
    "activations": 0.06,
    "active_users": 0.03,
    "transactions": 0.05,
    "gmv_usd": 0.05,
    "points_earned": 0.05,
    "rec_accuracy_pct": 0.8,
    "failed_recs": 0.08,
    "support_tickets": 0.12,
}


def generate(seed=42):
    """Return (weekly_df, feedback_df). Deterministic for a given seed."""
    rng = np.random.default_rng(seed)
    rows = []
    for i, week in enumerate(WEEKS):
        row = {"week": week}
        for col in KPI_COLUMNS:
            val = BASE[col] * (1 + GROWTH[col]) ** i
            val = val * (1 + rng.normal(0, NOISE[col]))
            if col in ("rec_accuracy_pct",):
                row[col] = round(float(np.clip(val, 80.0, 99.5)), 1)
            elif col == "gmv_usd":
                row[col] = round(float(val), 2)
            else:
                row[col] = int(round(val))
        rows.append(row)
    df = pd.DataFrame(rows)

    # --- Deliberate edge cases (deterministic, applied after generation) ---
    # W03: rec_accuracy missing.
    df.loc[df["week"] == "2026-W03", "rec_accuracy_pct"] = np.nan
    # W05: exact tie for top mover — force signups and transactions to the
    # same % change vs W04 by scaling them from the W04 values.
    w04 = df.loc[df["week"] == "2026-W04"].iloc[0]
    for col in ("signups", "transactions"):
        df.loc[df["week"] == "2026-W05", col] = int(round(w04[col] * 1.12))
    # W06: negative transactions — a data-quality fault.
    df.loc[df["week"] == "2026-W06", "transactions"] = -50
    # W07: recommendation accuracy dips below the 90% risk threshold.
    df.loc[df["week"] == "2026-W07", "rec_accuracy_pct"] = 87.0

    # --- Feedback: 3 snippets per week, seeded ---
    fb_rows = []
    for week in WEEKS:
        idx = rng.choice(len(FEEDBACK_POOL), size=3, replace=False)
        for j in idx:
            theme, text = FEEDBACK_POOL[j]
            fb_rows.append({"week": week, "theme": theme, "text": text})
    fb = pd.DataFrame(fb_rows)
    return df, fb


def save_synthetic(df, fb, out_dir):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_dir / "weekly_metrics.csv", index=False)
    fb.to_csv(out_dir / "feedback.csv", index=False)
    return out_dir / "weekly_metrics.csv", out_dir / "feedback.csv"


if __name__ == "__main__":
    df, fb = generate()
    print(df.to_string(index=False))
    print(fb.to_string(index=False))
